# ---- headings and captions
VOID = {'br', 'img', 'hr', 'input', 'meta', 'link', 'source', 'col', 'area', 'base', 'wbr'}
HEADING_TAGS = {'h1', 'h2', 'h3', 'h4', 'figcaption', 'summary'}
HEADING_CLASSES = {'cap', 'try-h', 'rules-h', 'chap-n', 'who-h', 'h'}


class Visible(HTMLParser):
    """visible text, alt/title/aria-label text, SVG text and headings of an HTML page"""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.text, self.attrs, self.headings = [], [], []
        self.skip = 0
        self.stack = []
        self.cur = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ('style', 'script'):
            self.skip += 1
        for k in ('alt', 'aria-label', 'title'):
            if a.get(k):
                self.attrs.append(a[k])
        cls = set((a.get('class') or '').split())
        head = tag in HEADING_TAGS or bool(cls & HEADING_CLASSES)
        if tag in VOID:
            if tag == 'br':
                self.text.append(' ')
                if self.cur is not None:
                    self.cur.append(' ')
            return   # a void tag (br, img, meta ...) has no end tag, so it must not go on the stack
        self.stack.append((tag, head))
        if head:
            self.cur = []

    def handle_endtag(self, tag):
        if tag in ('style', 'script') and self.skip:
            self.skip -= 1
        if self.stack:
            t, head = self.stack.pop()
            if head and self.cur is not None:
                s = re.sub(r'\s+', ' ', ''.join(self.cur)).strip()
                if s:
                    self.headings.append(s)
                self.cur = None

    def handle_data(self, data):
        if self.skip:
            return
        self.text.append(data)
        if self.cur is not None:
            self.cur.append(data)


def visible(htmltext):
    p = Visible()
    p.feed(htmltext)
    return ' '.join(p.text), p.attrs, p.headings


def corpora(listing_files):
    out = []  # (kind, name, text)
    for name, t in L.texts():
        out.append(('src', name, L.strip_code(t)))
    for fp in sorted(glob.glob(os.path.join(C.SRC, '*.html'))):
        if 'art-sheet' in fp or os.path.basename(fp).startswith('_'):
            continue
        t, attrs, heads = visible(open(fp, encoding='utf-8').read())
        out.append(('built', os.path.basename(fp), t + ' ' + ' '.join(attrs)))
        for h in heads:
            out.append(('heading', os.path.basename(fp), h))
    for fp in sorted(glob.glob(os.path.join(C.OUT, '*.pdf'))):
        txt = subprocess.run(['pdftotext', '-enc', 'UTF-8', fp, '-'], capture_output=True, text=True).stdout
        out.append(('pdf', os.path.basename(fp), txt))
        info = subprocess.run(['pdfinfo', fp], capture_output=True, text=True).stdout
        out.append(('pdfinfo', os.path.basename(fp), ' '.join(l.split(':', 1)[1] for l in info.splitlines() if l.split(':', 1)[0] in ('Title', 'Author', 'Subject', 'Keywords', 'Creator', 'Producer') and ':' in l)))
    for fp in sorted(glob.glob(os.path.join(C.OUT, 'epub', '*.epub'))):
        z = zipfile.ZipFile(fp)
        for n in z.namelist():
            if n.endswith(('.xhtml', '.opf', '.ncx')):
                raw = z.read(n).decode('utf-8')
                if n.endswith('.xhtml'):
                    t, attrs, heads = visible(raw)
                    out.append(('epub', os.path.basename(fp) + ':' + n, t + ' ' + ' '.join(attrs)))
                    for h in heads:
                        out.append(('heading', os.path.basename(fp) + ':' + n, h))
                else:
                    out.append(('epub', os.path.basename(fp) + ':' + n, htmlmod.unescape(re.sub(r'<[^>]+>', ' ', raw))))
    for lf in listing_files:
        out.append(('listing', os.path.basename(lf), open(lf, encoding='utf-8').read()))
    return out


def reader_listing_text():
    """the parts of the KDP listing that are copied to Amazon's pages for readers: titles, subtitles, descriptions, keywords, taglines"""
    import make_package as M
    parts = []
    for t in M.TITLES:
        parts += [t['name'], t['sub'], M.DESC[t['id']], ' '.join(M.KEYWORDS[t['id']]), ' '.join(M.TAGS[t['id']]), ' '.join(t['back'])]
    return re.sub(r'<[^>]+>', ' ', ' '.join(parts))


def load_allow():
    p = os.path.join(HERE, 'us_allow.txt')
    out = set()
    if os.path.exists(p):
        for ln in open(p, encoding='utf-8'):
            ln = ln.split('#')[0].strip().lower()
            if ln:
                out.add(ln)
    return out


def unknown_words(corp, allow):
    words = {}
    for kind, name, t in corp:
        if kind in ('listing', 'pdf', 'pdfinfo', 'heading') or name.endswith(('.opf', '.ncx')):
            continue   # the PDF words come from the built pages (checked there); the others are metadata and joined heading text
        for m in re.finditer(r"[A-Za-z](?:[A-Za-z'\u2019]*[A-Za-z])?", t):
            w = m.group(0).replace('’', "'")
            words.setdefault(w, (kind, name))
    todo = set()
    names = {c.lower() for c in CHARACTERS}
    for w in words:
        base = re.sub(r"'s$", '', w)
        if base.lower() in names or base.lower() in allow or w.lower() in allow:
            continue
        todo.add(w)
    r = subprocess.run(['node', os.path.join(HERE, 'spell.js')], input=json.dumps(sorted(todo)), capture_output=True, text=True)
    if r.returncode != 0:
        print('spell.js failed (set NODE_PATH to a folder with nspell and dictionary-en):', r.stderr[:300])
        return None
    bad = json.loads(r.stdout)
    return [(w, words[w]) for w in bad]


def main():
    listing_files = [a for a in sys.argv[1:] if a.endswith('.md')]
    corp = corpora(listing_files)
    allow = load_allow()
    problems, review = [], []
    names = [c for c in CHARACTERS]
    for kind, name, t in corp:
        if kind == 'heading':
            for c in names:
                if c != 'Moon' and re.search(r'\b' + re.escape(c) + r'\b', t):
                    if any(bt in t for bt in BOOK_TITLES):
                        continue
                    problems.append((kind, name, 'name in a heading or caption', t))
            continue
        if kind == 'listing':
            # private upload notes: only the British check applies to the whole file
            for m in re.finditer(FAIL[-1][1], t, FAIL[-1][2]):
                problems.append((kind, name, FAIL[-1][0], t[max(0, m.start() - 40):m.end() + 40].replace('\n', ' ')))
            continue
        for label, rx, flags in FAIL:
            if kind == 'src' and label == 'AI wording' and False:
                continue
            for m in re.finditer(rx, t, flags):
                ctx = t[max(0, m.start() - 40):m.end() + 40].replace('\n', ' ')
                if label.startswith('expert') and m.group(0) in ('Park', 'Ross', 'Stern', 'Gordon', 'Rogers') and False:
                    continue
                problems.append((kind, name, label, ctx))
        for m in re.finditer(NAME_NOTICE, t):
            review.append((kind, name, 'NAME ' + m.group(0), t[max(0, m.start() - 30):m.end() + 30].replace('\n', ' ')))
        for m in re.finditer(REVIEW, t, re.I):
            w = m.group(0).lower()
            if w in allow:
                continue
            review.append((kind, name, w, t[max(0, m.start() - 30):m.end() + 30].replace('\n', ' ')))
    # the reader-visible parts of the listing
    try:
        rl = reader_listing_text()
        for label, rx, flags in FAIL:
            for m in re.finditer(rx, rl, flags):
                problems.append(('listing-reader', 'descriptions and taglines', label, rl[max(0, m.start() - 40):m.end() + 40]))
    except Exception as e:  # pragma: no cover
        print('could not read the listing text:', e)
    unk = unknown_words(corp, allow)
    for p in problems:
        print('FAIL    %-9s %-40s %-26s %s' % p)
    seen = {}
    for kind, name, w, ctx in review:
        seen.setdefault(w, []).append((kind, name, ctx))
    for w, lst in sorted(seen.items()):
        k, n, c = lst[0]
        print('REVIEW  %-8s x%-3d %-6s %-30s %s' % (w, len(lst), k, n[:30], c))
    if unk:
        for w, (k, n) in unk:
            print('UNKNOWN %-22s %-6s %s' % (w, k, n))
    print('\n%d failure(s), %d review word(s), %d unknown word(s)' % (len(problems), len(seen), len(unk or [])))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
