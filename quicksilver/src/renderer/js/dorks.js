// Fill the placeholders. A missing {site}/{term} is left readable so the query still makes sense.
function dorkFill(q, { site = '', term = '' } = {}) {
  return q
    .replace(/\{site\}/g, site.trim() || 'example.com')
    .replace(/\{term\}/g, term.trim() || 'your search');
}
// Does a template need a field the user hasn't given yet?
const dorkNeeds = (q, kind) => new RegExp(`\\{${kind}\\}`).test(q);
// Build the search-engine URL for a finished query.
const DORK_ENGINES = {
  google: ['Google', (q) => `https://www.google.com/search?q=${encodeURIComponent(q)}`],
  bing: ['Bing', (q) => `https://www.bing.com/search?q=${encodeURIComponent(q)}`],
  ddg: ['DuckDuckGo', (q) => `https://duckduckgo.com/?q=${encodeURIComponent(q)}`],
  yandex: ['Yandex', (q) => `https://yandex.com/search/?text=${encodeURIComponent(q)}`],
};
function dorkUrl(q, engine = 'google') { return (DORK_ENGINES[engine] || DORK_ENGINES.google)[1](q); }

